import { readFile, mkdir, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";
import assert from "node:assert/strict";
import { chromium } from "../dashboard/node_modules/playwright/index.mjs";
const credentials = JSON.parse(await readFile(path.join(homedir(), ".codex/tmp/avila-experiments-deploy-20261027/credentials.json")));
const directory = new URL("../evidencias/screenshots/", import.meta.url);
await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const anonymous = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await anonymous.newPage();
  const response = await page.goto("https://ml.avilaops.com/evidencias/");
  assert.equal(response.status(), 200);
  await page.getByRole("heading", { name: "Evidência antes de confiança." }).waitFor();
  assert.equal(await page.getByRole("button").count(), 0);
  await page.screenshot({ path: new URL("public-desktop.png", directory).pathname.replace(/^\/([A-Z]:)/, "$1"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: new URL("public-mobile.png", directory).pathname.replace(/^\/([A-Z]:)/, "$1"), fullPage: true });
  const privateStatus = await anonymous.request.get("https://ml.avilaops.com/experiments/");
  assert.equal(privateStatus.status(), 401);
  const context = await browser.newContext({ httpCredentials: { username: credentials.username, password: credentials.password }, viewport: { width: 1440, height: 1100 } });
  const privatePage = await context.newPage();
  const errors = [];
  privatePage.on("pageerror", error => errors.push(error.message));
  assert.equal((await privatePage.goto("https://ml.avilaops.com/experiments/")).status(), 200);
  await privatePage.getByLabel("Casos da suíte (JSON)").waitFor();
  assert.equal(JSON.parse(await privatePage.getByLabel("Casos da suíte (JSON)").inputValue()).length, 14);
  await privatePage.locator("tbody button").first().click();
  await privatePage.getByRole("heading", { name: "Detalhe da execução" }).waitFor();
  await privatePage.screenshot({ path: new URL("deployed-private-desktop.png", directory).pathname.replace(/^\/([A-Z]:)/, "$1"), fullPage: true });
  await privatePage.setViewportSize({ width: 390, height: 844 });
  assert.equal(await privatePage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await privatePage.screenshot({ path: new URL("deployed-private-mobile.png", directory).pathname.replace(/^\/([A-Z]:)/, "$1"), fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(new URL("../evidencias/browser-deployed.json", import.meta.url), JSON.stringify({ public: 200, privateAnonymous: 401, privateAuthenticated: 200, initialCases: 14, desktop: true, mobile: true, consoleErrors: errors }, null, 2));
  console.log("Deployed browser checks passed: public anonymous, private authentication, desktop and mobile.");
} finally { await browser.close(); }
